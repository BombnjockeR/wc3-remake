"""Pack game files (models/textures) into assets/*.js so the game can load them even from file://.

usage: python3 pack_assets.py <name> <source_dir> [--rename old=new ...]
Every file under source_dir is stored under its relative path (backslashes, lowercase), e.g.
  units/human/footman/footman.mdx  ->  units\\human\\footman\\footman.mdx
Packs are split into ~16 MB files: assets/<name>-0.js, assets/<name>-1.js ...
"""
import base64, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
name, src = sys.argv[1], sys.argv[2]
renames = dict(a.split('=', 1) for a in sys.argv[3:] if '=' in a)
renames = {k.lower().replace('/', '\\'): v for k, v in renames.items()}
out_dir = os.path.join(ROOT, 'assets'); os.makedirs(out_dir, exist_ok=True)
for f in os.listdir(out_dir):
    if f.startswith(name + '-') and f.endswith('.js'):
        os.remove(os.path.join(out_dir, f))
packs, cur, size = [], {}, 0
for dp, dn, fn in os.walk(src):
    for f in sorted(fn):
        p = os.path.join(dp, f)
        rel = os.path.relpath(p, src).replace('/', '\\').lower()
        rel = renames.get(rel, rel)
        if rel in ('', '-'):
            continue
        data = base64.b64encode(open(p, 'rb').read()).decode()
        if size + len(data) > 16_000_000 and cur:
            packs.append(cur); cur, size = {}, 0
        cur[rel] = data; size += len(data)
if cur:
    packs.append(cur)
manifest = []
for i, pk in enumerate(packs):
    fn = f'{name}-{i}.js'
    with open(os.path.join(out_dir, fn), 'w') as fh:
        fh.write('(window.PYRO_ASSET_PACKS = window.PYRO_ASSET_PACKS || []).push(' + json.dumps(pk, separators=(',', ':')) + ');\n')
    manifest.append(fn)
    print(fn, len(pk), 'files')

# packs.js loads every pack in assets/ (works from file:// too)
import re  # noqa: E402
names = sorted(f for f in os.listdir(out_dir) if re.match(r'.+-\d+\.js$', f)) + ['wc3-files.js']
with open(os.path.join(out_dir, 'packs.js'), 'w') as fh:
    fh.write('// generated by tools/import_wc3.py / tools/pack_assets.py: loads every asset pack (works from file:// too)\n')
    for n in names:
        if os.path.exists(os.path.join(out_dir, n)):
            fh.write("document.write('<script src=\"assets/%s\"><\\/script>');\n" % n)
print('updated assets/packs.js')
